const rnd = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296; };
const around = (v, spread) => Math.round(v * (1 + (rnd() * 2 - 1) * spread));
const r2 = v => Math.round(v * 100) / 100;

