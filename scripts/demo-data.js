const pick = a => a[Math.floor(rnd() * a.length)];

function month(total, days) {
  const w = Array.from({ length: days }, () => (rnd() < 0.18 ? 0 : 0.3 + rnd() * rnd() * 3));
  const s = w.reduce((a, b) => a + b, 0) || 1;
  return w.map(x => r2(x / s * total));
}

