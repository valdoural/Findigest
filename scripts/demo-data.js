  const HIST = {};
  for (const m of ['2026-07', '2026-08', '2026-09']) {
    HIST[m] = {};
    for (const [c, v] of Object.entries(CATS)) { const x = around(v, 0.35); if (x > 300 && !(c === 'Путешествия' && m !== '2026-07')) HIST[m][c] = r2(x + rnd()); }
  }
  // текущий месяц по дням (снимок «на 26 число»), с двумя возвратами
