'use strict';
/** Подготовка текста к озвучке: числа, ₽, %, сокращения, годы, знаки. node test/speech-test.js */
const { prepare } = require('../src/main/ai/speech');
let bad = 0;
const t = (inp, want) => { const got = prepare(inp); const ok = want.every(w => got.includes(w)); if (!ok) bad++; console.log((ok ? '✓ ' : '✗ ') + inp + ' → ' + got); };
t('Траты 12 345 ₽', ['12345 рублей']);
t('Остаток 1 ₽, ставка 12%', ['1 рубль', '12 процентов']);
t('Капитал 3,4 млн ₽', ['3,4 миллиона рублей']);
t('Платёж 24 тыс/мес', ['тысячи в месяц']);
t('В 2026 году · по плану ≈ 5 млн', ['2026 году', ', по плану', 'примерно 5 миллионов']);
t('Рост +7% (за год)', ['плюс 7 процентов', ', за год']);
t('Т.е. экономия, т.к. меньше чеков', ['То есть', 'так как']);
process.exitCode = bad ? 1 : 0;
