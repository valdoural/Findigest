'use strict';
/**
 * Числа словами по-русски — для озвучки ответов помощника.
 * Голосовые движки (и голос Windows) читают «3 033» как «три ноль тридцать три», а «3,4 млн ₽» — по цифрам.
 * Здесь суммы, проценты, даты и годы превращаются в слова с правильным родом и склонением:
 *   12 345 ₽       → двенадцать тысяч триста сорок пять рублей
 *   1 234,56 ₽     → одна тысяча двести тридцать четыре рубля пятьдесят шесть копеек
 *   3,4 млн ₽      → три целых четыре десятых миллиона рублей;  1,5 млн → полтора миллиона;  2,5 тыс. → две с половиной тысячи
 *   12%            → двенадцать процентов;  4,4% → четыре целых четыре десятых процента
 *   29.10.2026     → двадцать девятое октября две тысячи двадцать шестого года
 *   в 2026 году    → в две тысячи двадцать шестом году
 */

const plural = (n, one, few, many) => { const a = Math.abs(n) % 10, b = Math.abs(n) % 100; return a === 1 && b !== 11 ? one : a >= 2 && a <= 4 && (b < 12 || b > 14) ? few : many; };

const U = { m: ['', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'], f: ['', 'одна', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'], n: ['', 'одно', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'] };
const TEEN = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать', 'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать'];
const TENS = ['', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят', 'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто'];
const HUND = ['', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот', 'шестьсот', 'семьсот', 'восемьсот', 'девятьсот'];

/** Единицы: формы для 1 / 2–4 / 5+, род, родительный ед. (для дробей: «три целых четыре десятых миллиона»). */
const UNIT = {
  rub: ['рубль', 'рубля', 'рублей', 'm', 'рубля'], kop: ['копейка', 'копейки', 'копеек', 'f', 'копейки'],
  pct: ['процент', 'процента', 'процентов', 'm', 'процента'], thou: ['тысяча', 'тысячи', 'тысяч', 'f', 'тысячи'],
  mln: ['миллион', 'миллиона', 'миллионов', 'm', 'миллиона'], mlrd: ['миллиард', 'миллиарда', 'миллиардов', 'm', 'миллиарда'],
};
const SCALES = [[1e9, UNIT.mlrd], [1e6, UNIT.mln], [1e3, UNIT.thou]];

function triple(n, g) {
  const h = Math.floor(n / 100), r = n % 100, out = [];
  if (h) out.push(HUND[h]);
  if (r >= 10 && r < 20) out.push(TEEN[r - 10]);
  else { if (r >= 20) out.push(TENS[Math.floor(r / 10)]); if (r % 10) out.push(U[g][r % 10]); }
  return out.join(' ');
}

/** Целое число словами; g — род: m (рубль, процент), f (тысяча, копейка), n (оно). */
function words(num, g = 'm') {
  let n = Math.round(Math.abs(+num));
  if (!isFinite(n)) return String(num);
  if (n === 0) return 'ноль';
  if (n >= 1e12) return String(num);
  const out = [];
  for (const [v, u] of SCALES) {
    const k = Math.floor(n / v);
    if (k) { out.push(triple(k, u[3]), plural(k, u[0], u[1], u[2])); n %= v; }
  }
  if (n) out.push(triple(n, g));
  return (num < 0 ? 'минус ' : '') + out.join(' ');
}

const FR = [null, ['десятая', 'десятых'], ['сотая', 'сотых'], ['тысячная', 'тысячных']];
/** Дробное число с единицей: «полтора миллиона», «две с половиной тысячи», «три целых четыре десятых процента». */
function withUnit(intStr, fracStr, unit, neg) {
  const i = +intStr, [one, few, many, g, gen] = unit;
  const sign = neg ? 'минус ' : '';
  let f = (fracStr || '').replace(/0+$/, '');
  if (!f) return `${sign}${words(i, g)} ${plural(i, one, few, many)}`;
  if (f === '5') {
    if (i === 0) return `${sign}пол${gen}`;
    if (i === 1) return `${sign}${g === 'f' ? 'полторы' : 'полтора'} ${few}`;
    return `${sign}${words(i, g)} с половиной ${plural(i, one, few, many)}`;
  }
  if (f.length > 3) f = f.slice(0, 3);
  const fn = +f, fw = FR[f.length];
  return `${sign}${words(i, 'f')} ${plural(i, 'целая', 'целых', 'целых')} ${words(fn, 'f')} ${plural(fn, fw[0], fw[1], fw[1])} ${gen}`;
}
/** Дробное число без единицы: «одна целая пять десятых». */
function decimal(intStr, fracStr, neg) {
  let f = (fracStr || '').replace(/0+$/, '');
  if (!f) return (neg ? 'минус ' : '') + words(+intStr);
  if (f.length > 3) f = f.slice(0, 3);
  const i = +intStr, fn = +f, fw = FR[f.length];
  return `${neg ? 'минус ' : ''}${words(i, 'f')} ${plural(i, 'целая', 'целых', 'целых')} ${words(fn, 'f')} ${plural(fn, fw[0], fw[1], fw[1])}`;
}

/* ---------- порядковые: даты и годы ---------- */
const OU = ['', 'перв', 'втор', 'трет', 'четвёрт', 'пят', 'шест', 'седьм', 'восьм', 'девят'];
const OT = ['десят', 'одиннадцат', 'двенадцат', 'тринадцат', 'четырнадцат', 'пятнадцат', 'шестнадцат', 'семнадцат', 'восемнадцат', 'девятнадцат'];
const OTENS = ['', '', 'двадцат', 'тридцат', 'сороков', 'пятидесят', 'шестидесят', 'семидесят', 'восьмидесят', 'девяност'];
const OHUND = ['', 'сот', 'двухсот', 'трёхсот', 'четырёхсот', 'пятисот', 'шестисот', 'семисот', 'восьмисот', 'девятисот'];
const STRESSED = new Set(['втор', 'шест', 'седьм', 'восьм', 'сороков']);
// формы: nom — именит. м. р. (год), gen — родит. (года, октября), prep — предл. (в году), neut — именит. ср. р. (число)
function end(stem, form) {
  if (stem === 'трет') return { nom: 'третий', gen: 'третьего', prep: 'третьем', neut: 'третье' }[form];
  return stem + { nom: STRESSED.has(stem) ? 'ой' : 'ый', gen: 'ого', prep: 'ом', neut: 'ое' }[form];
}
/** Порядковое числительное: 29 → двадцать девятое (neut), 2026 → две тысячи двадцать шестого (gen). */
function ordinal(num, form = 'nom') {
  const n = Math.round(Math.abs(num));
  if (n === 0) return 'нулев' + { nom: 'ой', gen: 'ого', prep: 'ом', neut: 'ое' }[form];
  const r = n % 100, h = Math.floor(n % 1000 / 100), th = Math.floor(n / 1000);
  if (r === 0 && h === 0) {   // 2000 → двухтысячный, 1000 → тысячный
    const pre = th === 1 ? '' : { 2: 'двух', 3: 'трёх', 4: 'четырёх', 5: 'пяти' }[th] || '';
    return end(pre + 'тысячн', form);
  }
  const head = [];
  if (th) head.push(words(th * 1000));
  if (r === 0) return [...head, end(OHUND[h], form)].join(' ');
  if (h) head.push(HUND[h]);
  if (r < 10) return [...head, end(OU[r], form)].join(' ');
  if (r < 20) return [...head, end(OT[r - 10], form)].join(' ');
  if (r % 10 === 0) return [...head, end(OTENS[r / 10], form)].join(' ');
  return [...head, TENS[Math.floor(r / 10)], end(OU[r % 10], form)].join(' ');
}
const MONTHS = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
const MONTHS_NOM = ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'];

/* ---------- текст целиком ---------- */
const NB = '(?<![\\d,.])';
const FEM = /^(позици|покупк|операци|квитанци|недел|минут|секунд|категори|цел[ьиейя]|ставк|запис|штук|строк|групп|карт[аыу]?$|ноч|копе|тысяч|подписк|поездк|услуг|трат[аы]?$|сумм|стать|вещ|книг|единиц|точк|ошибк|отметк|версия|верси)/;
const NEUT = /^(письм|мест|числ|окн|яблок|блюд|сообщени|правил|изменени|начислени)/;          // число начинается не внутри другого числа
const SCALE_KEY = k => (/^тыс/.test(k) ? UNIT.thou : /^млрд/.test(k) ? UNIT.mlrd : UNIT.mln);

function speakNumbers(src) {
  let t = String(src || '');
  t = t.replace(/(\d)[   ](?=\d{3}(?!\d))/g, '$1');                 // 1 234 567 → 1234567
  t = t.replace(/(\d)−(?=\d)/g, '$1–').replace(/−\s?(?=\d)/g, '-');            // типографский минус
  // даты: 29.10.2026, 29.10.26, на 23.10; месяц и год: 12.2025
  t = t.replace(new RegExp(NB + '(\\d{1,2})\\.(\\d{1,2})\\.(\\d{4}|\\d{2})(?![\\d,])', 'g'), (m, d, mo, y) => {
    if (+mo < 1 || +mo > 12 || +d < 1 || +d > 31) return m;
    const yy = y.length === 2 ? 2000 + +y : +y;
    return `${ordinal(+d, 'neut')} ${MONTHS[mo - 1]} ${ordinal(yy, 'gen')} года`;
  });
  t = t.replace(new RegExp(NB + '(\\d{2})\\.(\\d{4})(?![\\d,])', 'g'), (m, mo, y) => (+mo >= 1 && +mo <= 12 ? `${MONTHS_NOM[mo - 1]} ${ordinal(+y, 'gen')} года` : m));
  t = t.replace(new RegExp(NB + '(\\d{2})\\.(\\d{2})(?![\\d.,]|\\s*(?:₽|%|руб))', 'g'), (m, d, mo) => (+mo >= 1 && +mo <= 12 && +d >= 1 && +d <= 31 ? `${ordinal(+d, 'neut')} ${MONTHS[mo - 1]}` : m));
  // время 18:40
  t = t.replace(/(?<!\d)([01]?\d|2[0-3]):([0-5]\d)(?!\d)/g, (m, h, mi) => `${words(+h)} ${+mi ? words(+mi, 'f') : 'ноль ноль'}`);
  // годы: в 2026 году, 2025 год, 2024 года
  t = t.replace(/(?<![\d,.])(\d{4})\s+(год|году|года|годом)(?![а-яё])/g, (m, y, w) => `${ordinal(+y, w === 'года' ? 'gen' : w === 'году' ? 'prep' : 'nom')} ${w}`);
  // 3,4 млн ₽ · 24 тыс ₽ · 1,5 млрд рублей
  t = t.replace(new RegExp(NB + '(-)?(\\d+)(?:[.,](\\d+))?\\s*(тыс\\.?|млн\\.?|млрд\\.?)\\s*(?:₽|руб(?:\\.|лей|ля|ль)?(?![а-яё]))', 'g'),
    (m, neg, a, b, k) => `${withUnit(a, b, SCALE_KEY(k), !!neg)} рублей`);
  // 1234,56 ₽ · 3033 ₽ · 12 руб.
  t = t.replace(new RegExp(NB + '(-)?(\\d+)(?:[.,](\\d{1,2}))?\\s*(?:₽|руб(?:\\.|лей|ля|ль)?(?![а-яё]))', 'g'), (m, neg, a, b) => {
    const kop = b ? +(b.length === 1 ? b + '0' : b) : 0;
    return `${neg ? 'минус ' : ''}${words(+a)} ${plural(+a, ...UNIT.rub.slice(0, 3))}${kop ? ` ${words(kop, 'f')} ${plural(kop, ...UNIT.kop.slice(0, 3))}` : ''}`;
  });
  // 12% · 4,4 % · +7%
  t = t.replace(new RegExp(NB + '(-)?(\\d+)(?:[.,](\\d+))?\\s*%', 'g'), (m, neg, a, b) => withUnit(a, b, UNIT.pct, !!neg));
  // 3,4 млн · 120 тыс. (без рублей)
  t = t.replace(new RegExp(NB + '(-)?(\\d+)(?:[.,](\\d+))?\\s*(тыс\\.?|млн\\.?|млрд\\.?)(?![а-яё])', 'g'), (m, neg, a, b, k) => withUnit(a, b, SCALE_KEY(k), !!neg));
  // остальные числа: 216 → двести шестнадцать, 1,5 → одна целая пять десятых
  // род берём у следующего слова: «одна позиция», «две покупки», «одно письмо»
  t = t.replace(new RegExp(NB + '(-)?(\\d+)(?:,(\\d+))?(?![\\d])(?=(\\s+[а-яё]+)?)', 'g'), (m, neg, a, b, next) => {
    if (a.length > 12) return m;
    if (b) return decimal(a, b, !!neg);
    const w = (next || '').trim().toLowerCase();
    const g = FEM.test(w) ? 'f' : NEUT.test(w) ? 'n' : 'm';
    return (neg ? 'минус ' : '') + words(+a, g);
  });
  return t;
}

module.exports = { words, ordinal, withUnit, decimal, speakNumbers, plural };
